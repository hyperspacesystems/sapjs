// node build/bundle.mjs          writes src/version.js and every bundle in dist/
// node build/bundle.mjs --check  writes nothing; exits 1 naming each file that is missing or stale
import { build } from "esbuild";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { pluginBundle } from "./plugin.mjs";

const check = process.argv.includes("--check");
const root = fileURLToPath(new URL("../", import.meta.url));
const stale = [];

function emit(relative, text) {
  const file = root + relative;
  if (check) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== text) stale.push(relative);
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

async function bundle(options, outfile) {
  const result = await build({ ...options, absWorkingDir: root, outfile, write: false, logLevel: "warning" });
  emit(outfile, result.outputFiles[0].text);
}

const { version } = JSON.parse(readFileSync(root + "package.json", "utf8"));
emit("src/version.js", `// Generated by build/bundle.mjs from package.json. Do not edit.\nexport const VERSION = ${JSON.stringify(version)};\n`);

const common = {
  entryPoints: ["src/sap.js"],
  bundle: true,
  format: "iife",
  globalName: "Sap",
  // The entry assigns window.Sap itself; expose the default export as window.Sap.
  footer: { js: "if (typeof window !== 'undefined' && Sap && Sap.default) window.Sap = Sap.default;" },
};

await bundle(common, "dist/sap.js");
await bundle({ ...common, minify: true }, "dist/sap.min.js");

// The core sets window.Sap itself, and only when no other copy did. It needs its own
// global: inheriting "Sap" would make a classic script's `var Sap` overwrite the
// callable API src/core.js installs.
const core = { ...common, entryPoints: ["src/core.js"], globalName: "SapCoreBundle", footer: undefined };
await bundle(core, "dist/sap-core.js");
await bundle({ ...core, minify: true }, "dist/sap-core.min.js");

// One classic script per first party plugin, named by the manifest: the file the engine
// fetches from the sap-plugins/ folder beside it.
const { MANIFEST } = await import("../src/plugin-manifest.js");
const plugins = Object.values(MANIFEST).map((facts) => facts.file || facts.name);
for (const file of plugins) emit(`dist/sap-plugins/${file}.js`, await pluginBundle(`${root}src/plugins/${file}.js`, { minify: true }));
const pluginNote = plugins.length ? ` and dist/sap-plugins/ (${plugins.join(", ")})` : "";

if (check) {
  for (const file of stale) console.error(`stale or missing: ${file}`);
  if (stale.length) {
    console.error('Run "npm run build".');
    process.exit(1);
  }
  console.log(`dist/ is current with src/ (v${version})`);
} else {
  console.log(`built dist/sap.js, dist/sap.min.js, dist/sap-core.js and dist/sap-core.min.js${pluginNote} (v${version})`);
}
